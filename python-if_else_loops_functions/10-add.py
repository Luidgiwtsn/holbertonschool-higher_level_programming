#!/usr/bin/python3
"""
Module qui définit une fonction pour additionner deux entiers.
"""


def add(a, b):
    """
    Additionne deux entiers et renvoie le résultat.

    Arguments:
        a (int) : Le premier entier.
        b (int) : Le deuxième entier.

    Retour:
        int : La somme de a et b.
    """
    return a + b
