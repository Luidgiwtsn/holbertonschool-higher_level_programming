#!/usr/bin/python3
"""Module that defines a function to calculate a to the power of b."""


def pow(a, b):
    """
    Compute the value of a raised to the power b.

    Args:
        a (int or float): The base.
        b (int): The exponent (can be negative, zero, or positive).

    Returns:
        float: The result of a ** b.
    """
    return a ** b
