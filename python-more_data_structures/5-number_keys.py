#!/usr/bin/python3
"""Module qui définit une fonction pour compter les clés d'un dictionnaire."""


def number_keys(a_dictionary):
    """
    Retourne le nombre de clés dans un dictionnaire.

    Args:
        a_dictionary: Un objet dictionnaire.

    Returns:
        Le nombre de clés dans le dictionnaire.
    """
    return len(a_dictionary)
